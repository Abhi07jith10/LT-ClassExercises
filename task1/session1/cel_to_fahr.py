#4. Celsius to Fahrenheit
#Write a Python program to convert a temperature given in Celsius into Fahrenheit.
#Equation: Fahrenheit = (Celsius × 9 / 5) + 32

celsius=float(input("enter the temperature in celsius: "))

Fahrenheit=(celsius*9/5) + 32

print(f"The given temperature in Fahrenheit is :{Fahrenheit}")